// La langue de la page suit celle de l'interface : lecteurs d'ecran,
// cesure et correcteurs s'y fient.
const syncLang = (lng) => { document.documentElement.lang = (lng || 'en').split('-')[0] }
syncLang(i18n.language)
i18n.on('languageChanged', syncLang)

// Le francais et l'espagnol sont des fichiers separes, charges seulement quand
// on en a besoin. L'anglais reste inclus : c'est la langue de secours.
const LOADERS = {
  fr: () => import('./locales/fr.js'),
  es: () => import('./locales/es.js'),
}

async function ensureLanguage(lng) {
  const base = (lng || 'en').split('-')[0]
  if (LOADERS[base] && !i18n.hasResourceBundle(base, 'translation')) {
    const mod = await LOADERS[base]()
    i18n.addResourceBundle(base, 'translation', mod.default)
  }
}

export const i18nReady = ensureLanguage(i18n.language).catch(() => {})

export async function setLanguage(code) {
  await ensureLanguage(code)
  return i18n.changeLanguage(code)
}

export default i18n
